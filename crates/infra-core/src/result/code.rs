//! Error-code metadata and macros for declaring typed error-code enums.

use std::fmt::{Debug, Display};

/// Static metadata for an application error code.
///
/// Equality intentionally compares only `domain` and `code`, so the stable
/// machine-readable identity is not affected by message text changes.
#[derive(Debug, Copy, Clone)]
pub struct AppErrCode {
	/// Static domain prefix, for example `SYS`.
	pub domain: &'static str,
	/// Domain-local numeric error code.
	pub code: u16,
	/// Static human-readable message associated with the code.
	pub message: &'static str,
}

impl PartialEq for AppErrCode {
	fn eq(&self, other: &Self) -> bool {
		self.domain == other.domain && self.code == other.code
	}
}

impl Eq for AppErrCode {}

/// Trait implemented by typed error-code enums.
///
/// Implementors provide static metadata through [`ErrCodeTrait::err_code`] and
/// a precomputed static domain/code string through
/// [`ErrCodeTrait::domain_code`].
pub trait ErrCodeTrait: Debug + Display + Copy + Sync + Send + 'static {
	/// Returns the static metadata for this error code.
	fn err_code(self) -> AppErrCode;

	/// Returns the static domain prefix.
	fn domain(self) -> &'static str {
		self.err_code().domain
	}

	/// Returns the numeric error code within the domain.
	fn code(self) -> u16 {
		self.err_code().code
	}

	/// Returns the static human-readable message.
	fn message(self) -> &'static str {
		self.err_code().message
	}

	/// Returns a static domain/code identifier.
	///
	/// Implementations generated by `define_app_error_codes!` return
	/// `000000` for success code `0`, otherwise `"<domain>:<code>"`.
	fn domain_code(self) -> &'static str;
}

/// Generates the static domain/code string used by generated error-code enums.
#[doc(hidden)]
#[macro_export]
macro_rules! __domain_code_literal {
	($domain:literal, 0) => {
		"000000"
	};
	($domain:literal, $code:literal) => {
		concat!($domain, ":", $code)
	};
}

/// Declares typed error-code enums and implements the standard error traits.
///
/// For each enum definition, this macro generates:
/// - the enum itself with `Debug`, `Copy`, `Clone`, `PartialEq`, and `Eq`;
/// - [`ErrCodeTrait`] with static [`AppErrCode`] metadata;
/// - [`std::fmt::Display`] in the `[DOMAIN:CODE] message` format;
/// - `From<Enum>` for [`AppError`](crate::result::AppError).
///
/// Attributes placed on the enum or variants are preserved.
///
/// # Examples
///
/// ```rust,ignore
/// infra_core::define_app_error_codes! {
///     SysErr("SYS") {
///         Success = (0, "Success"),
///         ConfigLoadFailed = (1001, "Config load failed"),
///     }
/// }
/// ```
#[macro_export]
macro_rules! define_app_error_codes {
    (
        $(
            $(#[$enum_attr:meta])*
            $enum_name:ident ($domain:literal) {
                $(
                    $(#[$variant_attr:meta])*
                    $variant_name:ident = ($code:tt, $message:expr),
                )*
            }
        )*
    ) => {
        $(
            $(#[$enum_attr])*
            #[derive(Debug, Copy, Clone, PartialEq, Eq)]
            pub enum $enum_name {
                $(
                    $(#[$variant_attr])*
                    $variant_name,
                )*
            }

            impl $crate::result::ErrCodeTrait for $enum_name {
                fn err_code(self) -> $crate::result::AppErrCode {
                    match self {
                        $(
                            $enum_name::$variant_name => $crate::result::AppErrCode {
                                domain: $domain,
                                code: $code,
                                message: $message,
                            },
                        )*
                    }
                }

                fn domain_code(self) -> &'static str {
                    match self {
                        $(
                            $enum_name::$variant_name => $crate::__domain_code_literal!($domain, $code),
                        )*
                    }
                }
            }

            impl std::fmt::Display for $enum_name {
                fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                    use $crate::result::ErrCodeTrait;

                    let code = (*self).err_code();
                    write!(f, "[{}:{}] {}", code.domain, code.code, code.message)
                }
            }

            impl From<$enum_name> for $crate::result::AppError {
                fn from(value: $enum_name) -> Self {
                    $crate::result::AppError::from_code(value)
                }
            }
        )*
    };
}

define_app_error_codes! {
	/// System-level infrastructure error codes.
	SysErr("SYS") {
		/// Operation completed successfully.
		Success = (0, "Success"),
		// cfg
		/// Configuration loading failed.
		ConfigLoadFailed = (1001, "Config load failed"),
		/// Configuration file does not exist at the expected path.
		NoCfgFile = (1002, "Config file not found"),
		// params
		/// Request or function parameters failed validation.
		InvalidParams = (2001, "Invalid params"),
	}
}

#[cfg(test)]
mod tests {
	use super::{ErrCodeTrait, SysErr};
	use crate::result::AppError;

	#[test]
	fn sys_err_exposes_static_code_data() {
		let code = SysErr::ConfigLoadFailed.err_code();

		assert_eq!(code.domain, "SYS");
		assert_eq!(code.code, 1001);
		assert_eq!(code.message, "Config load failed");
	}

	#[test]
	fn sys_err_exposes_static_domain_code() {
		assert_eq!(SysErr::ConfigLoadFailed.domain_code(), "SYS:1001");
	}

	#[test]
	fn sys_err_success_domain_code_is_zero() {
		assert_eq!(SysErr::Success.domain_code(), "000000");
	}

	#[test]
	fn app_err_code_equality_ignores_message() {
		assert_eq!(
			SysErr::ConfigLoadFailed.err_code(),
			crate::result::AppErrCode {
				domain: "SYS",
				code: 1001,
				message: "different message",
			}
		);
	}

	#[test]
	fn sys_err_converts_to_app_error() {
		let err: AppError = SysErr::ConfigLoadFailed.into();

		assert_eq!(
			err,
			AppError::ErrCode {
				domain: "SYS",
				code: 1001,
				message: "Config load failed".into(),
			}
		);
	}
}
